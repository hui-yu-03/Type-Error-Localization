"""Joint solving against solving the independent parts separately (localizer/parallel.py).

    python bench/parallel_bench.py [--jobs 4]

Programs of 8 independent modules (bench/generate.py --modules 8) with 4 or 8
mistakes, 2,000 and 8,000 lines, 2 seeds: the time to the first smallest MCS
(including encoding and slicing) for the joint formula, for the parts one
after the other, and for the parts in parallel, and the time to localize the
program again after an edit of one module (the parts cache).  Every method
must find the same cost.  Writes results/parallel.md.
"""

from __future__ import annotations

import argparse
import statistics
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT))

import evaluate as ev  # noqa: E402
from generate import generate  # noqa: E402
from localizer import mcs, parallel  # noqa: E402
from localizer.encode import encode  # noqa: E402
from localizer.slicing import slice_to_conflicts  # noqa: E402

RESULTS = ROOT / "results"


def program_with_mistakes(lines: int, seed: int, k: int):
    src = generate(lines, seed, modules=8)
    with tempfile.TemporaryDirectory() as d:
        base = Path(d) / "base.js"
        base.write_text(src)
        sample = ev.sample_mistakes(str(base), k, seed)
    bad = ev.apply_mistakes(src, sample["mistakes"])
    return bad, ev.program_from_json(ev.infer_source(bad), bad)


def joint(program) -> tuple[float, int]:
    t0 = time.time()
    enc, _ = slice_to_conflicts(encode(program))
    first = next(iter(mcs.make("oll", enc).enumerate(limit=1)))
    return time.time() - t0, first.cost


def by_parts(program, jobs: int) -> tuple[float, int, int]:
    parallel._cache.clear()
    t0 = time.time()
    _, cost, conflicting = parallel.smallest_mcs(program, jobs=jobs)
    return time.time() - t0, cost, conflicting


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=4)
    args = ap.parse_args()
    rows = []
    for lines in (2000, 8000):
        for k in (4, 8):
            for seed in (1, 2):
                src, program = program_with_mistakes(lines, seed, k)
                tj, cj = joint(program)
                t1, c1, parts = by_parts(program, 1)
                tp, cp, _ = by_parts(program, args.jobs)
                # an edit of one module: a new line in the first module moves all the others
                edited = src.replace("\n", "\nconst edit__1 = 1;\n", 1)
                program2 = ev.program_from_json(ev.infer_source(edited), edited)
                t0 = time.time()
                parallel.smallest_mcs(program2, jobs=args.jobs)
                te = time.time() - t0
                assert cj == c1 == cp, (lines, k, seed, cj, c1, cp)
                rows.append((lines, k, seed, parts, tj, t1, tp, te))
                print(rows[-1], flush=True)
    out = ["# Solving independent parts separately\n",
           f"Generated by `python bench/parallel_bench.py --jobs {args.jobs}`. Programs of 8 independent modules; "
           "seconds to the first smallest MCS, including encoding and slicing (median of 2 seeds). All methods "
           "found the same cost on every program. \"Edit\" is the time to localize again after a change, with the "
           "results of the unchanged parts cached.\n",
           "| lines | mistakes | conflicting parts | joint | parts, 1 process | parts, " + str(args.jobs)
           + " processes | after an edit |", "|---|---|---|---|---|---|---|"]
    for lines in (2000, 8000):
        for k in (4, 8):
            rs = [r for r in rows if r[0] == lines and r[1] == k]
            med = lambda i: statistics.median(r[i] for r in rs)  # noqa: E731
            out.append(f"| {lines:,} | {k} | {med(3):.1f} | {med(4):.1f} | {med(5):.1f} | {med(6):.1f} | {med(7):.1f} |")
    text = "\n".join(out) + "\n"
    (RESULTS / "parallel.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
