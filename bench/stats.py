"""Confidence intervals and significance tests for the localization results.

    python bench/stats.py

For every corpus, the top-1 and top-3 accuracy of the main methods with a 95%
confidence interval, and exact McNemar tests between pairs of methods on the
same mistakes.  Mistakes of the same program (or, for FixJS, of the same
commit) are not independent, so the intervals come from a cluster bootstrap
that resamples whole programs (commits).  Writes results/significance.md.
"""

from __future__ import annotations

import csv
import json
import random
import sys
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RESULTS = ROOT / "results"

BOOT = 2000


def cluster_bootstrap(values: list[float], groups: list[str], n: int = BOOT, seed: int = 0) -> tuple[float, float]:
    """95% percentile interval of the mean, resampling whole groups."""
    by: dict[str, list[float]] = {}
    for v, g in zip(values, groups):
        by.setdefault(g, []).append(v)
    keys = list(by)
    rng = random.Random(seed)
    means = []
    for _ in range(n):
        total = count = 0
        for _ in keys:
            vs = by[keys[rng.randrange(len(keys))]]
            total += sum(vs)
            count += len(vs)
        means.append(total / count)
    means.sort()
    return means[int(0.025 * n)], means[int(0.975 * n) - 1]


def mcnemar(a: list[bool], b: list[bool]) -> tuple[int, int, float]:
    """Exact McNemar test: (a right and b wrong, a wrong and b right, two-sided p)."""
    n01 = sum(1 for x, y in zip(a, b) if x and not y)
    n10 = sum(1 for x, y in zip(a, b) if y and not x)
    n = n01 + n10
    if n == 0:
        return n01, n10, 1.0
    k = min(n01, n10)
    p = 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n
    return n01, n10, min(1.0, p)


def _hit(rank, k: int) -> bool:
    try:
        return rank not in (None, "", "None") and int(float(rank)) <= k
    except ValueError:
        return False


def single_mistakes(corpus: str) -> tuple[list[dict], dict]:
    rows = [r for r in csv.DictReader((RESULTS / f"{corpus}.csv").open())
            if r.get("setting") == "open" and r.get("detected") == "True"]
    methods = {
        "first conflict (solver.js)": "rank_first_conflict_js",
        "MCS card, latest first": "rank_card-late",
        "MCS learned": "rank_learned",
        "latest first + re-inference + hints": "rank_card-late+reinfer+hints",
    }
    return rows, methods


def fixjs(name: str) -> tuple[list[dict], dict]:
    path = RESULTS / f"{name}.jsonl"
    if not path.exists():
        return [], {}
    sys.path.insert(0, str(HERE))
    import fixjs as fx

    rows = [json.loads(line) for line in path.open() if line.strip()]
    rows = [r for r in rows if r.get("buggy_ill_typed") and r.get("fixed_well_typed") and r["similarity"] >= fx.SAME]
    for r in rows:
        r["base"] = r["name"].split("/", 1)[-1].split("_", 1)[0]  # the commit
    methods = {m: f"rank: {m}" for m in ("first conflict (solver.js)", "first conflict (SMT order)",
                                          "MCS card, latest first", "full pipeline")}
    return rows, methods


def section(title: str, rows: list[dict], methods: dict, reference: str, random_key: str | None = None) -> list[str]:
    if not rows:
        return []
    groups = [r["base"] for r in rows]
    out = [f"## {title}\n", f"{len(rows)} mistakes in {len(set(groups))} programs (clusters).\n",
           "| method | top-1 (%) [95% CI] | top-3 (%) [95% CI] |", "|---|---|---|"]
    hits = {}
    for m, col in methods.items():
        cells = []
        for k in (1, 3):
            h = [_hit(r.get(col), k) for r in rows]
            hits[(m, k)] = h
            lo, hi = cluster_bootstrap([float(x) for x in h], groups)
            cells.append(f"{100 * sum(h) / len(h):.0f} [{100 * lo:.0f}–{100 * hi:.0f}]")
        out.append(f"| {m} | " + " | ".join(cells) + " |")
    if random_key:
        cells = []
        for k in (1, 3):
            v = [float(r[f"{random_key}{k}"]) for r in rows]
            lo, hi = cluster_bootstrap(v, groups)
            cells.append(f"{100 * sum(v) / len(v):.0f} [{100 * lo:.0f}–{100 * hi:.0f}]")
        out.append("| random line (expected) | " + " | ".join(cells) + " |")
    out += ["", f"McNemar tests against {reference} (top-1): mistakes only it ranks first / only the other "
            "method ranks first, two-sided p.\n", "| method | only " + reference + " | only the method | p |",
            "|---|---|---|---|"]
    for m in methods:
        if m == reference:
            continue
        a, b, p = mcnemar(hits[(reference, 1)], hits[(m, 1)])
        out.append(f"| {m} | {a} | {b} | {p:.2g} |")
    return out + [""]


def main() -> None:
    out = ["# Confidence intervals and significance\n",
           f"Generated by `python bench/stats.py`. 95% confidence intervals by a cluster bootstrap ({BOOT} "
           "resamples of whole programs, for FixJS of whole commits); exact McNemar tests on the same mistakes.\n"]
    for corpus, title in (("mutants", "Test suite, one mistake"), ("generated", "Generated programs, one mistake")):
        rows, methods = single_mistakes(corpus)
        out += section(title, rows, methods, "MCS card, latest first")
    for name, title in (("fixjs", "FixJS real bug fixes"), ("fixjs_relaxed", "FixJS real bug fixes, relaxed type system")):
        rows, methods = fixjs(name)
        out += section(title, rows, methods, "MCS card, latest first", random_key="random_top")
    text = "\n".join(out)
    (RESULTS / "significance.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
