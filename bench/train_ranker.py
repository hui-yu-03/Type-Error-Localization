"""Train and evaluate the learned tie-breaker.

    python bench/train_ranker.py

Reads the tiers of candidates (with features, localizer/features.py) stored by
the single-mistake experiments in results/{mutants,generated}.csv and

  * evaluates every tie-breaking rule on the same stored tiers: earliest
    first, latest first, fewest constraints, random, and the learned model;
  * evaluates the learned model only on held-out data: 5-fold cross-validation
    grouped by base program (mutants of one program are never split between
    training and test), and across corpora (train on one, test on the other);
  * trains the final model on all data -> localizer/ranking_model.json;
  * writes results/learned.md.

The model is a conditional logit: within a tier T, P(c | T) = exp(w.x_c) /
sum_{c' in T} exp(w.x_c'), fitted by gradient ascent with L2 regularization on
the tier that contains the mistake (when it has more than one candidate).
"""

from __future__ import annotations

import csv
import json
import math
import random
import sys
import zlib
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from localizer.features import FEATURES, MODEL_PATH  # noqa: E402

RESULTS = ROOT / "results"
POS, LOGC = FEATURES.index("position"), FEATURES.index("log_constraints")


def load(corpus: str) -> list[dict]:
    rows = []
    for r in csv.DictReader((RESULTS / f"{corpus}.csv").open()):
        if r.get("setting") != "open" or r.get("detected") != "True" or not r.get("tiers"):
            continue
        rows.append({"corpus": corpus, "base": r["base"], "op": r["op"], "tiers": json.loads(r["tiers"])})
    return rows


def dot(w, x):
    return sum(a * b for a, b in zip(w, x))


def train(rows: list[dict], l2: float = 0.01, iters: int = 1500, lr: float = 0.5) -> list[float]:
    """Conditional logit on the tiers that contain the mistake (more than one candidate)."""
    groups = []
    for r in rows:
        for tier in r["tiers"]:
            if any(c["y"] for c in tier):
                if len(tier) > 1:
                    groups.append(tier)
                break
    if not groups:
        return [0.0] * len(FEATURES)
    X = np.array([c["x"] for t in groups for c in t], dtype=float)
    y = np.array([c["y"] for t in groups for c in t], dtype=bool)
    sizes = np.array([len(t) for t in groups])
    starts = np.concatenate([[0], np.cumsum(sizes)[:-1]])
    w = np.zeros(X.shape[1])
    for _ in range(iters):
        s = X @ w
        e = np.exp(s - np.repeat(np.maximum.reduceat(s, starts), sizes))
        p = e / np.repeat(np.add.reduceat(e, starts), sizes)
        py = np.repeat(np.add.reduceat(np.where(y, p, 0.0), starts), sizes)
        coef = np.where(y, p / py, 0.0) - p  # d log P(mistake in the tier's top) / d score
        w += lr * (X.T @ coef / len(groups) - l2 * w)
    return [float(v) for v in w]


def rank_of_target(tiers: list, key) -> int | None:
    """Rank of the mistake line when every tier is ordered by key (smaller
    first); distinct lines are counted, ties within a candidate pessimistically."""
    seen: set = set()
    for tier in tiers:
        for c in sorted(tier, key=key):
            seen.update(c["lines"])
            if c["y"]:
                return len(seen)
    return None


RULES = {
    "earliest first": lambda c: c["x"][POS],
    "latest first": lambda c: -c["x"][POS],
    "fewest constraints, then latest": lambda c: (c["x"][LOGC], -c["x"][POS]),
}


def topk(rows: list[dict], key, k: int) -> float:
    return sum(1 for r in rows if (rk := rank_of_target(r["tiers"], key)) is not None and rk <= k) / len(rows)


def random_topk(rows: list[dict], k: int, trials: int = 200) -> float:
    rng = random.Random(0)
    hits = 0
    for r in rows:
        for _ in range(trials):
            noise = {}
            rk = rank_of_target(r["tiers"], lambda c: noise.setdefault(id(c), rng.random()))
            hits += rk is not None and rk <= k
    return hits / (len(rows) * trials)


def learned_key(w):
    return lambda c: (-dot(w, c["x"]), -c["x"][POS])


def cross_validated(rows: list[dict], folds: int = 5) -> list[tuple[dict, list[float]]]:
    """(row, weights of the model that did not see the row's program)."""
    fold = lambda r: zlib.crc32(r["base"].encode()) % folds  # noqa: E731
    out = []
    for f in range(folds):
        w = train([r for r in rows if fold(r) != f])
        out += [(r, w) for r in rows if fold(r) == f]
    return out


def pct(x: float) -> str:
    return f"{100 * x:.0f}"


def main() -> None:
    data = {c: load(c) for c in ("mutants", "generated")}
    lines = ["# Learned tie-breaking\n", "Generated by `python bench/train_ranker.py`. Top-1 / top-3 (%) of the "
             "mistake line on the ill-typed single-mistake mutants (open records, line granularity). All rules order "
             "the same stored tiers of candidates; the learned model is evaluated only on programs it was not trained "
             "on.\n"]
    header = "| rule | " + " | ".join(f"{c} (n={len(rs)})" for c, rs in data.items()) + " |"
    lines += [header, "|---|" + "---|" * len(data)]
    table = {}
    for name, key in RULES.items():
        table[name] = [f"{pct(topk(rs, key, 1))} / {pct(topk(rs, key, 3))}" for rs in data.values()]
    table["random"] = [f"{pct(random_topk(rs, 1))} / {pct(random_topk(rs, 3))}" for rs in data.values()]
    cv = []
    for rs in data.values():
        pairs = cross_validated(rs)
        t1 = sum(1 for r, w in pairs if (k := rank_of_target(r["tiers"], learned_key(w))) and k <= 1) / len(pairs)
        t3 = sum(1 for r, w in pairs if (k := rank_of_target(r["tiers"], learned_key(w))) and k <= 3) / len(pairs)
        cv.append(f"**{pct(t1)}** / {pct(t3)}")
    table["learned (5-fold CV by program)"] = cv
    corpora = list(data)
    cross = []
    for c in corpora:
        other = [r for o in corpora if o != c for r in data[o]]
        w = train(other)
        cross.append(f"{pct(topk(data[c], learned_key(w), 1))} / {pct(topk(data[c], learned_key(w), 3))}")
    table["learned (trained on the other corpus)"] = cross
    for name, cells in table.items():
        lines.append(f"| {name} | " + " | ".join(cells) + " |")

    # per mistake kind, cross-validated, both corpora together
    allrows = [r for rs in data.values() for r in rs]
    pairs = cross_validated(allrows)
    ops = sorted({r["op"] for r in allrows})
    lines += ["\nBy kind of mistake (both corpora, top-1 %):\n",
              "| rule | " + " | ".join(ops) + " |", "|---|" + "---|" * len(ops)]
    for name, key in list(RULES.items()):
        lines.append(f"| {name} | " + " | ".join(
            pct(topk([r for r in allrows if r["op"] == op], key, 1)) for op in ops) + " |")
    cells = []
    for op in ops:
        ps = [(r, w) for r, w in pairs if r["op"] == op]
        cells.append(pct(sum(1 for r, w in ps if (k := rank_of_target(r["tiers"], learned_key(w))) and k <= 1) / len(ps)))
    lines.append("| learned (5-fold CV) | " + " | ".join(cells) + " |")

    w = train(allrows)
    MODEL_PATH.write_text(json.dumps({
        "features": FEATURES,
        "weights": [round(v, 4) for v in w],
        "trained_on": {c: len(rs) for c, rs in data.items()},
    }, indent=1) + "\n")
    lines += ["\nWeights of the final model (trained on all mutants; positive = more likely the mistake):\n",
              "| feature | weight |", "|---|---|"]
    for f, v in sorted(zip(FEATURES, w), key=lambda p: -abs(p[1])):
        lines.append(f"| {f} | {v:+.2f} |")
    (RESULTS / "learned.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
